import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { RunResults } from "@/components/agentic/run-results";
import { RunTimeline } from "@/components/agentic/run-timeline";
import { MarkdownReport } from "@/components/kredal/markdown-report";
import { SiteFooter } from "@/components/marketing/site-footer";
import { SiteNav } from "@/components/marketing/site-nav";
import { getRunWithEvents } from "@/lib/agentic/store/firestore";
import type { StoredRun } from "@/lib/agentic/view";

export const metadata: Metadata = { title: "Agent run" };
export const dynamic = "force-dynamic";

/** A stored run, replayed exactly as it happened — the audit trail of a run. */
export default async function RunPage({ params }: { params: Promise<{ runId: string }> }) {
  const { runId } = await params;
  if (!/^[0-9a-f-]{36}$/i.test(runId)) notFound();
  const run = (await getRunWithEvents(runId)) as StoredRun | null;
  if (!run) notFound();

  return (
    <div className="flex flex-1 flex-col">
      <SiteNav />
      <main className="mx-auto w-full max-w-6xl flex-1 px-6 pb-20">
        <div className="border-b border-border pb-8 pt-14">
          <Link href="/agent" className="text-caption underline underline-offset-2">
            ← Run the agents again
          </Link>
          <p className="eyebrow mt-6">Agent run · {run.id.slice(0, 8)}</p>
          <h1 className="mt-2 text-h1 font-semibold">{run.caseTitle}</h1>
          <p className="mt-2 text-body-sm text-muted-foreground">
            {run.status === "done" ? "Completed" : run.status === "failed" ? "Failed" : "Running"}
            {run.durationMs ? ` in ${(run.durationMs / 1000).toFixed(1)}s` : ""}
            {run.chaos ? " · with an injected failure" : ""}
            {run.heals ? ` · ${run.heals} heal event${run.heals === 1 ? "" : "s"}` : ""}
            {` · started ${new Date(run.startedAt).toLocaleString("en-GB", { dateStyle: "medium", timeStyle: "short", timeZone: "UTC" })} UTC`}
          </p>
          {run.error && <p className="mt-3 text-body-sm text-risk-high-foreground">{run.error}</p>}
        </div>

        <div className="grid gap-10 pt-10 lg:grid-cols-[minmax(0,1fr)_minmax(0,1.1fr)]">
          <section>
            <p className="eyebrow">Timeline</p>
            <div className="mt-4">
              <RunTimeline events={run.events} />
            </div>
          </section>
          {run.result && (
            <section>
              <p className="eyebrow">Conclusions</p>
              <div className="mt-4">
                <RunResults summary={run.result} runId={run.id} answers={run.answers} />
              </div>
            </section>
          )}
        </div>

        {run.result?.packMarkdown && (
          <section className="mt-16 border-t border-border pt-10">
            <p className="eyebrow">Bank application pack</p>
            <p className="mt-2 text-body-sm text-muted-foreground">
              Generated by the Advisor from the findings above. A readiness assessment and application pack — not a promise
              of approval.
            </p>
            <div className="mt-6 rounded-lg border border-border bg-card p-6">
              <MarkdownReport content={run.result.packMarkdown} />
            </div>
          </section>
        )}
      </main>
      <SiteFooter />
    </div>
  );
}
